import fs from 'node:fs';
import assert from 'node:assert/strict';
import vm from 'node:vm';
import { compileSource, build } from './build.mjs';
const root = new URL('../', import.meta.url);
const raw = fs.readFileSync(new URL('source/original.html', root), 'utf8');
const a = compileSource(raw), b = compileSource(raw);
assert.deepEqual(a.files, b.files);
const map = JSON.parse(a.assets['assets/resources/import/c5/c5ea826b-8bc4-4e9d-8974-6490a40235a2.json'])[5][0][2];
assert.equal(map.length, 12);
assert.equal(map.reduce((n, box) => n + box.itemList.filter(Boolean).length + box.plateListNum.slice(0,-1).reduce((s,v)=>s+v,0) + box.lastPlateList.filter(Boolean).length, 0), 120);
const core = a.assets['assets/main/index.js'];
const match = core.match(/\.checkFull=function\(\)\{([\s\S]*?)\},\w+\.updateItems=/);
assert.ok(match, 'native triple matching method');
let emissions=0;
const ctx = vm.createContext({d:{ins:{playAudio(){}}},h:{combo:'combo'},o:{emit(){emissions++;}},_:{checkDoneNum:'checkDoneNum'}});
const check = vm.runInContext('(function(){'+match[1]+'})', ctx);
for (const types of [[1,1,2],[-1,-1,-1]]) check.call({_items:types.map(_type=>({_type}))});
assert.equal(emissions,0,'mixed and empty grills do not match');
check.call({_items:[1,1,1].map(_type=>({_type}))});
assert.equal(emissions,1,'three identical skewers match once');
for (const [name, content] of Object.entries(a.files)) if(name.endsWith('.js')) new vm.Script(content);
build();
console.log('grill-sort-origin: source, 120-item conservation, native matching and deterministic build passed');
